export type ShipClassId =
  | 'COASTAL_PATROL'
  | 'DESTROYER'
  | 'CRUISER'
  | 'BATTLESHIP'
  | 'SUBMARINE'
  | 'AIRCRAFT_CARRIER'
  | 'DREDGER_ICEBREAKER'
  | 'TACTICAL_SUPPORT';

export interface ShipDef {
  id: string;
  name: string;
  tier: number;                  // 1 to 10
  shipClass: ShipClassId;
  inspiration: string;
  length: number;                // Meters
  beam: number;                  // Meters
  mass: number;                  // Metric tonnes
  maxHp: number;
  armor: number;                 // Armor mitigation points
  maxForwardSpeed: number;       // m/s
  maxReverseSpeed: number;       // m/s
  accelerationRate: number;      // m/s^2
  decelerationRate: number;      // m/s^2
  turnRateMax: number;           // rad/s
  driftCoefficient: number;      // Lateral hydrodynamic slip factor
  draft: number;                 // Keel draft in meters
  radarCrossSection: number;     // RCS factor
  cavitationThresholdSpeed: number; // m/s
  isIcebreaker: boolean;
  canSubmerge: boolean;
  mounts: WeaponMountDef[];
  specialAbilities: string[];
  traits: string[];
}

const TIER_XP_TABLE: Record<number, number> = {
  1: 0,
  2: 145,
  3: 330,
  4: 560,
  5: 830,
  6: 1150,
  7: 1520,
  8: 1950,
  9: 2450,
  10: 3100,
};

/**
 * Calculates XP required to unlock a tier.
 * Matches balanced progression benchmarks (e.g. 630 delta for T7, 940 delta for T8, 1,430 delta for T9).
 */
export function getRequiredXpForTier(tier: number): number {
  if (tier <= 1) return 0;
  if (tier in TIER_XP_TABLE) return TIER_XP_TABLE[tier];
  return Math.round(100 * Math.pow(tier - 1, 1.35) + 45 * (tier - 1));
}

